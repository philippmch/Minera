"""Write the profile-clustering bank fixture read by
minera_profile_clustering_parity_tests.

    python scripts/generate-profile-clustering-bank-tests.py \\
        docs/profile-clustering-bank.json.gz \\
        --output src/backend/tests/fixtures/profile_clustering_bank.txt

Line format: `C <name>`; one `T <region> <event>...` line per trace, an event
being `activity;amount;kind` with `-` for a missing value; then `X <Error>`,
or one `O <cluster>|<cluster>...` line per observed outcome, a cluster being
comma-separated trace positions.
"""
import argparse
import gzip
import hashlib
import json
from pathlib import Path


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('bank', type=Path)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    raw = args.bank.read_bytes()
    bank = json.loads(gzip.decompress(raw))
    lines = [f'# Generated by scripts/generate-profile-clustering-bank-tests.py from {args.bank.as_posix()}',
             f'# Bank SHA256 {hashlib.sha256(raw).hexdigest()}; do not edit.']
    for case in bank['cases']:
        lines.append(f"C {case['name']}")
        for trace in case['traces']:
            events = [';'.join([e['activity'], repr(e['amount']) if 'amount' in e else '-', e.get('kind', '-')])
                      for e in trace['events']]
            lines.append(' '.join(['T', trace['region'] or '-'] + events))
        outcome = case['outcome']
        if 'error' in outcome:
            lines.append(f"X {outcome['error']}")
            continue
        for observed in outcome.get('observed', [outcome]):
            lines.append('O ' + '|'.join(','.join(map(str, cluster)) for cluster in observed['clusters']))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'{len(lines)} lines')


if __name__ == '__main__':
    main()
