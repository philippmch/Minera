"""Write the ILP discovery bank fixture used by
minera_ilp_discovery_parity_tests.

    python scripts/generate-ilp-discovery-bank-tests.py \\
        docs/ilp-discovery-bank.json.gz \\
        --output src/backend/tests/ilp_discovery_bank_cases.inc

Each case becomes `C <name> <model> <alpha>`, `S <start> <end>`, one
`P <producer> <consumer>` line per explicit causal pair, one `T <activity>...`
line per trace (log order), then per observed outcome `O`, followed by either
`E <class> <message>` or one `X <name> <label or ->` line per transition and
one `Q <name> <producers> <consumers>` line per place (comma-separated names,
`-` when empty). Every net is checked here to carry unit arcs, one token in
`source` and one token in `sink`.
"""
import argparse
import gzip
import hashlib
import json
from pathlib import Path

START, END = '\u25b6', '\u25a0'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('bank', type=Path)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    raw = args.bank.read_bytes()
    bank = json.loads(gzip.decompress(raw))
    lines = []
    for case in bank['cases']:
        lines.append(f"C {case['name']} {case['model']} {case['alpha']!r}")
        lines.append(f"S {case.get('start', '▶')} {case.get('end', '■')}")
        for producer, consumer in case.get('causal', []):
            lines.append(f'P {producer} {consumer}')
        for trace in case.get('log_traces', case['traces']):
            lines.append(' '.join(['T'] + trace))
        for outcome in case['observed']:
            lines.append('O')
            if 'error' in outcome:
                lines.append(f"E {outcome['error'][0]} {outcome['error'][1]}")
                continue
            net = outcome['net']
            assert net['initial'] == [['source', 1]] and net['final'] == [['sink', 1]], case['name']
            assert net['weights'] in ([1], []), case['name']
            for name, label in net['transitions']:
                lines.append(f"X {name} {'-' if label is None else label}")
            for name, inputs, outputs in net['places']:
                lines.append(f"Q {name} {','.join(inputs) or '-'} {','.join(outputs) or '-'}")
    body = ''.join('"' + line.replace('\\', '\\\\').replace('"', '\\"') + '",\n' for line in lines)
    args.output.write_text(
        '// Generated by scripts/generate-ilp-discovery-bank-tests.py from\n'
        f'// {args.bank.as_posix()}; do not edit.\n'
        f'// Bank SHA256 {hashlib.sha256(raw).hexdigest()}.\n' + body, encoding='utf-8')
    print(f'{len(lines)} lines')


if __name__ == '__main__':
    main()
