"""Write the seeded Monte Carlo bank fixture read by
minera_monte_carlo_numpy_parity_tests.

    python scripts/generate-monte-carlo-numpy-bank-tests.py \\
        docs/monte-carlo-numpy-bank.json.gz \\
        --output src/backend/tests/fixtures/monte_carlo_numpy_bank.txt

Line format: `C <name> <places> <seed> <simulations> <arrival> <capacity>`;
`T <label or -> <weight> <law> <parameters...>` per transition in order
(`T <label or -> - fitted` when the case fits its map from a source log, whose
traces follow as `L <activity>@<second>...`; the arrival is `-` when inferred);
`A <transition> <place> <in|out>` per arc; `I`/`F <place> <tokens>` for the
markings; then per distinct reference outcome `O` followed by `X <Error>`, or
by one `R <activity>@<epoch microseconds>...` line per trace, `E <case times>`
and `M <median> <total>`. Floats use Python repr.
"""
import argparse
from datetime import datetime
import gzip
import hashlib
import json
from pathlib import Path


def micros(text):
    moment = datetime.fromisoformat(text)
    epoch = datetime(1970, 1, 1, tzinfo=moment.tzinfo)
    delta = moment - epoch
    return (delta.days * 86400 + delta.seconds) * 1000000 + delta.microseconds


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('bank', type=Path)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    raw = args.bank.read_bytes()
    bank = json.loads(gzip.decompress(raw))
    lines = [f'# Generated by scripts/generate-monte-carlo-numpy-bank-tests.py from {args.bank.as_posix()}',
             f'# Bank SHA256 {hashlib.sha256(raw).hexdigest()}; do not edit.']
    for case in bank['cases']:
        places = {name: index for index, name in enumerate(case['places'])}
        transitions = {name: index for index, (name, _) in enumerate(case['transitions'])}
        arrival = repr(case['arrival']) if 'arrival' in case else '-'
        lines.append(f"C {case['name']} {len(places)} {case['seed']} {case['simulations']} "
                     f"{arrival} {case['capacity']}")
        for name, label in case['transitions']:
            if 'laws' not in case:
                lines.append(f"T {label or '-'} - fitted")
                continue
            law = case['laws'][name]
            lines.append(' '.join(['T', label or '-', repr(float(case['weights'][name])), law[0]]
                                  + [repr(float(value)) for value in law[1:]]))
        for trace in case.get('traces', []):
            lines.append(' '.join(['L'] + [f'{label}@{second}' for label, second in trace]))
        for source, target in case['arcs']:
            if source in transitions:
                lines.append(f'A {transitions[source]} {places[target]} out')
            else:
                lines.append(f'A {transitions[target]} {places[source]} in')
        for tag, marking in [('I', case['initial']), ('F', case['final'])]:
            for place, tokens in marking.items():
                lines.append(f'{tag} {places[place]} {tokens}')
        for outcome in case['observed']:
            lines.append('O')
            if 'error' in outcome:
                lines.append(f"X {outcome['error']}")
                continue
            for trace in outcome['traces']:
                lines.append(' '.join(['R'] + [f'{activity}@{micros(stamp)}' for activity, stamp in trace]))
            lines.append(' '.join(['E'] + [repr(value) for value in outcome['cases_ex_time']]))
            lines.append(f"M {outcome['median_cases_ex_time']!r} {outcome['total_cases_time']!r}")
    args.output.write_text('\n'.join(lines) + '\n', encoding='utf-8')


if __name__ == '__main__':
    main()
