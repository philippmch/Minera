"""Turns docs/ocel-links-bank.json.gz into the cases included by
src/backend/tests/test_ocel_links_parity.cpp: one compact JSON
document per case and call (in raw-literal pieces), parsed at run time (a brace-initialized fixture of this
size takes the compiler too long).

    python -I -B scripts/generate-ocel-links-tests.py \
        docs/ocel-links-bank.json.gz \
        --output src/backend/tests/ocel_links_cases.inc
"""
import argparse
import gzip
import hashlib
import json
from pathlib import Path


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('bank', type=Path)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    raw = args.bank.read_bytes()
    bank = json.loads(gzip.decompress(raw))
    lines = ['// Generated by scripts/generate-ocel-links-tests.py from',
             f'// {args.bank.as_posix()}; do not edit.',
             f'// Bank SHA256 {hashlib.sha256(raw).hexdigest()}.']
    for case in bank['cases']:
        # One document per call keeps every document within the literal limits.
        for call, expected in case['calls'].items():
            data = {k: v for k, v in case.items() if k not in ('name', 'calls')}
            document = {'name': case['name'], 'data': data, 'call': call, 'expected': expected}
            text = json.dumps(document, separators=(',', ':'), sort_keys=True, allow_nan=False,
                              ensure_ascii=False)
            # Adjacent raw literals concatenate; each piece stays below the
            # 16 KB literal limit of some compilers and the whole below 64 KB.
            if ')J"' in text or len(text) > 60000:
                raise SystemExit(f'{case["name"]} cannot be embedded as one string')
            pieces = [text[start:start + 15000] for start in range(0, len(text), 15000)]
            lines.append(' '.join(f'R"J({piece})J"' for piece in pieces) + ',')
    args.output.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
