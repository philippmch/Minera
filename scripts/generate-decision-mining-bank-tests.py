"""Write the decision-mining bank fixture read by
minera_decision_mining_parity_tests.

    python scripts/generate-decision-mining-bank-tests.py \\
        docs/decision-mining-bank.json.gz \\
        --output src/backend/tests/fixtures/decision_mining_bank.txt

Line format: `C <name>`; `N <pnml on one line>`; one
`T <region> <size> <event>...` line per trace, an event being
`activity;amount;kind;flag` with `-` for a missing value; per decision point
`P <place> <label,label>` followed by `X <Error>` when the table call raises,
or `H <column>|<dtype>...` and one `R <target> <cell>...` line per row
(`-` null, `t`/`f` booleans) and `K <class>...`; then `D <tree outcome>`.
"""
import argparse
import gzip
import hashlib
import json
from pathlib import Path


def token(value):
    if value is None:
        return '-'
    if value is True:
        return 't'
    if value is False:
        return 'f'
    return repr(value) if isinstance(value, float) else str(value)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('bank', type=Path)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    raw = args.bank.read_bytes()
    bank = json.loads(gzip.decompress(raw))
    lines = [f'# Generated by scripts/generate-decision-mining-bank-tests.py from {args.bank.as_posix()}',
             f'# Bank SHA256 {hashlib.sha256(raw).hexdigest()}; do not edit.']
    for case in bank['cases']:
        assert len(case['observed']) == 1, case['name']
        outcome = case['observed'][0]
        lines.append(f"C {case['name']}")
        lines.append('N ' + ' '.join(case['pnml'].split('\n')))
        for trace in case['traces']:
            events = [';'.join([event['activity']] + [token(event.get(key)) for key in ('amount', 'kind', 'flag')])
                      for event in trace['events']]
            lines.append(' '.join(['T', trace['region'], str(trace['size'])] + events))
        for place, entry in sorted(outcome['points'].items()):
            lines.append(f"P {place} {','.join(entry['labels'])}")
            table = entry['table']
            if 'error' in table:
                lines.append(f"X {table['error']}")
            else:
                lines.append(' '.join(['H'] + [f'{c}|{d}' for c, d in zip(table['columns'], table['dtypes'])]))
                for target, row in zip(table['targets'], table['rows']):
                    lines.append(' '.join(['R', str(target)] + [token(v) for v in row]))
                lines.append(' '.join(['K'] + table['classes']))
            tree = entry['tree']
            lines.append('D ' + (tree if isinstance(tree, str) else '!' + tree['error']))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'{len(lines)} lines')


if __name__ == '__main__':
    main()
