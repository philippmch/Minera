"""Write the OCEL LLM-abstraction bank fixture read by
minera_llm_ocel_abstractions_parity_tests.

    python scripts/generate-llm-ocel-abstractions-bank-tests.py \\
        docs/llm-ocel-abstractions-bank.json.gz \\
        --output src/backend/tests/fixtures/llm_ocel_abstractions_bank.txt

Line format: `C <name>`; one `B <object> <type>` line per object and one
`E <event> <activity> <minute> <object,...>` line per event (`-` for no
objects); then per call `K <call>` followed by `X <Error>` or `O <text>`, the
text with backslashes and newlines escaped as `\\\\` and `\\n`.
"""
import argparse
import gzip
import hashlib
import json
from pathlib import Path


def escape(text):
    return text.replace('\\', '\\\\').replace('\n', '\\n')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('bank', type=Path)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    raw = args.bank.read_bytes()
    bank = json.loads(gzip.decompress(raw))
    lines = [f'# Generated by scripts/generate-llm-ocel-abstractions-bank-tests.py from {args.bank.as_posix()}',
             f'# Bank SHA256 {hashlib.sha256(raw).hexdigest()}; do not edit.']
    for case in bank['cases']:
        lines.append(f"C {case['name']}")
        for object_id, object_type in case['ocel']['objects']:
            lines.append(f'B {object_id} {object_type}')
        for event_id, activity, minute, objects in case['ocel']['events']:
            lines.append(f"E {event_id} {activity} {minute} {','.join(objects) or '-'}")
        for call, outcome in case['calls'].items():
            lines.append(f'K {call}')
            if 'error' in outcome:
                lines.append(f"X {outcome['error']}")
            else:
                lines.append('O ' + escape(outcome['text']))
    args.output.write_text('\n'.join(lines) + '\n', encoding='utf-8')


if __name__ == '__main__':
    main()
