#!/usr/bin/env python3
"""Turn the reviewer's delta-comparison.json (recheck of 65572296) into the
C++ case table src/backend/tests/recheck_65572296_cases.inc.

Usage: generate-recheck-65572296-fixture.py <delta-comparison.json> <out.inc>
"""
import json
import sys

comparison, out_path = sys.argv[1], sys.argv[2]
comp = json.load(open(comparison))
out = []
out.append('// Generated by scripts/generate-recheck-65572296-fixture.py from the')
out.append("// reviewer's delta-comparison.json (saved inputs and public outputs of the")
out.append('// recheck of 65572296, 2026-10-28). Do not edit.')
out.append('// Cells: kind i (int), u (unsigned int), f (float), b (bool), s (text).')


def cell(v):
    if isinstance(v, bool):
        return ('b', 'true' if v else 'false')
    if isinstance(v, int):
        return ('u' if v > 9223372036854775807 else 'i', str(v))
    if isinstance(v, float):
        return ('f', repr(v))
    return ('s', v)


def c(k, t):
    return "{'%s',%s}" % (k, json.dumps(t))


out.append('const std::vector<DeltaCase> kDeltaCases{')
for case in comp:
    inp = case['input']
    ref = case['reference']
    expected = json.dumps(ref['value'], separators=(',', ':')) if ref['ok'] else ref['error_type'] + ': ' + ref['error']
    ok = 'true' if ref['ok'] else 'false'
    if inp['kind'] == 'batches':
        rows = ['{' + ','.join(c(*cell(v)) for v in row[:3]) + '}' for row in inp['rows']]
        out.append('  {%s,"batches","",{%s},%d,%s,%s},' % (json.dumps(inp['id']), ','.join(rows), inp['minimum'], ok, json.dumps(expected)))
    else:
        rows = ['{' + c(*cell(v)) + '}' for v in inp['values']]
        out.append('  {%s,"network",%s,{%s},0,%s,%s},' % (json.dumps(inp['id']), json.dumps(inp['role']), ','.join(rows), ok, json.dumps(expected)))
out.append('};')
open(out_path, 'w').write('\n'.join(out) + '\n')
print(len(comp), 'cases')
