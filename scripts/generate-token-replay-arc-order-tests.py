"""Turns docs/token-replay-arc-order-bank.json.gz into the C++ cases included by
src/backend/tests/test_token_replay_arc_order_parity.cpp.

    python -I -B scripts/generate-token-replay-arc-order-tests.py \
        docs/token-replay-arc-order-bank.json.gz \
        --output src/backend/tests/token_replay_arc_order_cases.inc
"""
import argparse
import gzip
import hashlib
import json
from pathlib import Path


def text(value):
    return json.dumps(value)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('bank', type=Path)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    raw = args.bank.read_bytes()
    bank = json.loads(gzip.decompress(raw))
    lines = ['// Generated by scripts/generate-token-replay-arc-order-tests.py from',
             f'// {args.bank.as_posix()}; do not edit.',
             f'// Bank SHA256 {hashlib.sha256(raw).hexdigest()}.']
    for case in bank['cases']:
        if 'replay' not in case:
            continue
        rows = []
        for trace, row in zip(case['traces'], case['replay']):
            trace_text = '{' + ', '.join(text(a) for a in trace) + '}'
            if 'activated' not in row:
                state = 'kSkipped' if ('unstable' in row or 'unresolved' in row) else 'kError'
                rows.append(f'  {{{trace_text}, {state}, {{}}, 0, 0, 0, 0, false}}')
                continue
            activated = '{' + ', '.join(text(a) for a in row['activated']) + '}'
            rows.append(f"  {{{trace_text}, kRow, {activated}, {row['missing']}, {row['consumed']}, "
                        f"{row['remaining']}, {row['produced']}, {'true' if row['fit'] else 'false'}}}")
        lines.append(f'{{{text(case["name"])},\n R"PNML({case["pnml"].strip()})PNML",\n {{\n'
                     + ',\n'.join(rows) + '}},')
    args.output.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
