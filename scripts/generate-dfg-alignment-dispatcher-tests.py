"""Turns docs/dfg-alignment-dispatcher-bank.json.gz into the cases included by
src/backend/tests/test_dfg_alignment_dispatcher_parity.cpp: one compact JSON
document per case, parsed at run time (a brace-initialized fixture of this
size takes the compiler too long).

    python -I -B scripts/generate-dfg-alignment-dispatcher-tests.py \
        docs/dfg-alignment-dispatcher-bank.json.gz \
        --output src/backend/tests/dfg_alignment_dispatcher_cases.inc
"""
import argparse
import gzip
import hashlib
import json
from pathlib import Path


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('bank', type=Path)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    raw = args.bank.read_bytes()
    bank = json.loads(gzip.decompress(raw))
    lines = ['// Generated by scripts/generate-dfg-alignment-dispatcher-tests.py from',
             f'// {args.bank.as_posix()}; do not edit.',
             f'// Bank SHA256 {hashlib.sha256(raw).hexdigest()}.']
    for case in bank['cases']:
        text = json.dumps(case, separators=(',', ':'), sort_keys=True, allow_nan=False)
        if ')J"' in text or len(text) > 16000:
            raise SystemExit(f'{case["name"]} cannot be embedded as one raw string')
        lines.append(f'R"J({text})J",')
    args.output.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
