"""Generate native model-quality equivalence vectors from the public capture.

Reads docs/evaluation-reference-fixtures.json (written by
capture-evaluation-reference.py) and emits
src/backend/tests/evaluation_reference_cases.inc. No reference calls.
"""
import argparse
import json
import math
import re
from pathlib import Path

VALUE, ERROR, UNRESOLVED = 'kValue', 'kError', 'kUnresolved'


def number(value):
    if isinstance(value, dict) and 'float' in value:
        return {'nan': 'kNaN', 'inf': 'kInf', '-inf': '-kInf'}[value['float']]
    value = float(value)
    assert math.isfinite(value)
    return repr(value)


def expect(result, keys=None):
    if 'unresolved' in result:
        return f'{{{UNRESOLVED}, {{}}}}'
    if 'error' in result:
        return f'{{{ERROR}, {{}}}}'
    value = result['value']
    values = [value] if keys is None else [value[key] for key in keys]
    return f'{{{VALUE}, {{{", ".join(number(v) for v in values)}}}}}'


def fitness_auto(result):
    if 'value' not in result:
        return expect(result)
    value = result['value']
    alignment = 'averageFitness' in value
    return (f'{{{VALUE}, {{{1.0 if alignment else 0.0}, {number(value["percentage_of_fitting_traces"])}, '
            f'{number(value["average_trace_fitness"])}, {number(value["log_fitness"])}}}}}')


def raw(text, delimiter):
    # Compact inter-tag whitespace and split into adjacent literals so every
    # piece stays below MSVC's per-literal limit.
    text = re.sub(r'>\s+<', '><', text.strip())
    assert f'){delimiter}"' not in text
    pieces = [text[i:i + 8000] for i in range(0, len(text), 8000)] or ['']
    return '\n'.join(f'R"{delimiter}({piece}){delimiter}"' for piece in pieces)


TOKEN = ['percentage_of_fitting_traces', 'average_trace_fitness', 'log_fitness']
COMPOSITE = ['precision', 'generalization', 'simplicity', 'metricsAverageWeight', 'fscore']


def composite(result):
    if 'value' not in result:
        return expect(result)
    value = result['value']
    values = [value['fitness'][key] for key in TOKEN] + [value[key] for key in COMPOSITE]
    return f'{{{VALUE}, {{{", ".join(number(v) for v in values)}}}}}'


def generate(data):
    assert data['reference'] == '2.7.22'
    lines = ['// Generated by scripts/generate-evaluation-reference-tests.py from',
             '// docs/evaluation-reference-fixtures.json; do not edit.',
             f'// Corpus SHA256 {data["corpus_sha256"]}.']
    for case in data['observations']:
        r = case['results']
        traces = ', '.join('{' + ', '.join(json.dumps(a) for a in trace) + '}' for trace in case['traces'])
        fields = [
            json.dumps(case['name']),
            raw(case['pnml'], 'PNML'),
            '{' + traces + '}',
            expect(r['fitness_token'], TOKEN),
            expect(r['fitness_alignment'], TOKEN),
            fitness_auto(r['fitness_auto']),
            expect(r['precision_token']),
            expect(r['precision_alignment']),
            expect(r['precision_automaton']),
            expect(r['precision_auto']),
            expect(r['generalization_token']),
            expect(r['simplicity_arc_degree']),
            expect(r['simplicity_extended_cardoso']),
            expect(r['simplicity_extended_cyclomatic']),
            composite(r['composite']),
        ]
        lines.append('{' + ',\n '.join(fields) + '},')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--input', type=Path, default=Path('docs/evaluation-reference-fixtures.json'))
    parser.add_argument('--output', type=Path, default=Path('src/backend/tests/evaluation_reference_cases.inc'))
    args = parser.parse_args()
    args.output.write_text(generate(json.loads(args.input.read_text(encoding='utf-8'))), encoding='utf-8')


if __name__ == '__main__':
    main()
