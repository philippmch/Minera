"""Write the label-splitting bank fixture used by
minera_label_splitting_parity_tests.

    python scripts/generate-label-splitting-bank-tests.py \\
        docs/label-splitting-bank.json.gz \\
        --output src/backend/tests/label_splitting_bank_cases.inc

Each case becomes `C <name>`, one `T <activity>...` line per trace and one
`R <config> <label>...` line per observed outcome (`R <config> !<Error>` for a
raising call). Activities and labels never contain spaces.
"""
import argparse
import gzip
import hashlib
import json
from pathlib import Path


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('bank', type=Path)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    raw = args.bank.read_bytes()
    bank = json.loads(gzip.decompress(raw))
    lines = []
    for case in bank['cases']:
        lines.append(f"C {case['name']}")
        for trace in case['traces']:
            assert all(' ' not in a for a in trace)
            lines.append('T ' + ' '.join(trace))
        for config, call in case['calls'].items():
            for outcome in call.get('observed', [call]):
                if 'error' in outcome:
                    lines.append(f"R {config} !{outcome['error']}")
                else:
                    assert outcome['index'] == list(range(len(outcome['index'])))
                    lines.append(' '.join(['R', config] + outcome['labels']))
    body = ''.join(f'"{line}",\n' for line in lines)
    args.output.write_text(
        f'// Generated by scripts/generate-label-splitting-bank-tests.py from\n'
        f'// {args.bank.as_posix()}; do not edit.\n'
        f'// Bank SHA256 {hashlib.sha256(raw).hexdigest()}.\n' + body, encoding='utf-8')
    print(f'{len(lines)} lines')


if __name__ == '__main__':
    main()
