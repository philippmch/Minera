"""Turns docs/ocel-nets-bank.json.gz into the cases included by
src/backend/tests/test_ocel_nets_parity.cpp: one compact JSON document per
case and call (in raw-literal pieces), parsed at run time. The outcomes a call
showed under the four hash seeds share most fields (the OCDFG annotations), so
each document holds the fields common to every outcome once and only the
differing fields per outcome.

    python -I -B scripts/generate-ocel-nets-tests.py \
        docs/ocel-nets-bank.json.gz \
        --output src/backend/tests/ocel_nets_cases.inc
"""
import argparse
import gzip
import hashlib
import json
from pathlib import Path


def factor(outcomes):
    errors = sorted({o['error'] for o in outcomes if 'error' in o})
    values = [o['value'] for o in outcomes if 'value' in o]
    common = {}
    if values:
        for key in values[0]:
            if all(key in v and v[key] == values[0][key] for v in values):
                common[key] = values[0][key]
    variants = [{k: v for k, v in value.items() if k not in common} for value in values]
    return {'errors': errors, 'common': common, 'variants': variants}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('bank', type=Path)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    raw = args.bank.read_bytes()
    bank = json.loads(gzip.decompress(raw))
    lines = ['// Generated by scripts/generate-ocel-nets-tests.py from',
             f'// {args.bank.as_posix()}; do not edit.',
             f'// Bank SHA256 {hashlib.sha256(raw).hexdigest()}.']
    for case in bank['cases']:
        for call, expected in case['calls'].items():
            outcomes = expected['observed'] if 'observed' in expected else [expected]
            document = {'name': case['name'], 'real': case['real'], 'call': call,
                        'expected': factor(outcomes)}
            text = json.dumps(document, separators=(',', ':'), sort_keys=True, allow_nan=False,
                              ensure_ascii=False)
            # Adjacent raw literals concatenate; each piece stays below the
            # 16 KB literal limit of some compilers and the whole below 64 KB.
            if ')J"' in text or len(text) > 60000:
                raise SystemExit(f'{case["name"]} {call} cannot be embedded as one string ({len(text)})')
            pieces = [text[start:start + 15000] for start in range(0, len(text), 15000)]
            lines.append(' '.join(f'R"J({piece})J"' for piece in pieces) + ',')
    args.output.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
