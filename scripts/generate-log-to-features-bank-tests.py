"""Write the log-to-features bank fixture read by
minera_log_to_features_parity_tests.

    python scripts/generate-log-to-features-bank-tests.py \\
        docs/log-to-features-bank.json.gz \\
        --output src/backend/tests/fixtures/log_to_features_bank.txt

Line format: `C <name>`; one `T <region> <size> <event>...` line per trace, an
event being `activity;minute;resource;amount;kind` with `-` for a missing
value; then per configuration `F <config>` followed by `X <Error>`, or by
`N <name>...` and `R <value>...` rows (`R <trace> <value>...` per event for
EVENT_BASED, `-` for NaN; TEMPORAL rows start with the bucket's ISO
timestamp and use the bank's minute scale). Column order moving with the hash seed keeps the
first observation; every observation is the same table up to column order.
"""
import argparse
import gzip
import hashlib
import json
from pathlib import Path


def token(value):
    if isinstance(value, str):
        return value
    return '-' if value is None else repr(float(value))


def canonical(outcome):
    if 'error' in outcome:
        return json.dumps(outcome)
    order = sorted(range(len(outcome['names'])), key=lambda i: outcome['names'][i])
    def pick(row):
        return [pick(item) for item in row] if row and isinstance(row[0], list) else [row[i] for i in order]
    return json.dumps([[outcome['names'][i] for i in order], [pick(row) for row in outcome['rows']]])


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('bank', type=Path)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    raw = args.bank.read_bytes()
    bank = json.loads(gzip.decompress(raw))
    lines = [f'# Generated by scripts/generate-log-to-features-bank-tests.py from {args.bank.as_posix()}',
             f'# Bank SHA256 {hashlib.sha256(raw).hexdigest()}; do not edit.']
    for case in bank['cases']:
        lines.append(f"C {case['name']}")
        for trace in case['traces']:
            events = [';'.join([e['activity'], str(e['minute']), e['resource'],
                                '-' if 'amount' not in e else repr(e['amount']), e.get('kind', '-')])
                      for e in trace['events']]
            lines.append(' '.join(['T', trace['region'], str(trace['size'])] + events))
        for config, outcome in case['calls'].items():
            if 'observed' in outcome:
                assert len({canonical(o) for o in outcome['observed']}) == 1, (case['name'], config)
                outcome = outcome['observed'][0]
            lines.append(f'F {config}')
            if 'error' in outcome:
                lines.append(f"X {outcome['error']}")
                continue
            lines.append(' '.join(['N'] + outcome['names']))
            event_based = bank['configs'][config]['variant'] == 'EVENT_BASED'
            for index, row in enumerate(outcome['rows']):
                if event_based:
                    for event in row:
                        lines.append(' '.join(['R', str(index)] + [token(v) for v in event]))
                else:
                    lines.append(' '.join(['R'] + [token(v) for v in row]))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'{len(lines)} lines')


if __name__ == '__main__':
    main()
