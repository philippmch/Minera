"""Write src/backend/python_unicode_alnum.hpp: the code point ranges where
str.isalnum() holds in the running interpreter (run it with the pinned
reference interpreter, Python 3.11)."""
import sys
from pathlib import Path


def ranges(predicate):
    out, start = [], None
    for code in range(0x110001):
        hit = code <= 0x10FFFF and predicate(code)
        if hit and start is None:
            start = code
        if not hit and start is not None:
            out.append((start, code - 1))
            start = None
    return out


def table(name, items):
    rows = ',\n'.join('    {0x%X, 0x%X}' % item for item in items)
    return f'inline constexpr CodeRange {name}[] = {{\n{rows},\n}};\n'


alnum = ranges(lambda c: chr(c).isalnum())
text = f'''#pragma once

// Generated by scripts/generate-python-unicode-alnum.py from Python
// {sys.version.split()[0]}; do not edit.

#include <algorithm>
#include <iterator>

namespace minera::detail {{

struct CodeRange {{
  char32_t first, last;
}};

{table('kPythonAlnumRanges', alnum)}
inline bool python_isalnum(char32_t code) {{
  const auto* end = std::end(kPythonAlnumRanges);
  const auto* at = std::upper_bound(std::begin(kPythonAlnumRanges), end, code,
                                    [](char32_t value, const CodeRange& range) {{ return value < range.first; }});
  return at != std::begin(kPythonAlnumRanges) && code <= std::prev(at)->last;
}}

}}  // namespace minera::detail
'''
Path(__file__).resolve().parent.parent.joinpath('src/backend/python_unicode_alnum.hpp').write_text(text)
print(len(alnum))
