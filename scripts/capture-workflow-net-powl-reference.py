"""Capture workflow-net to POWL observations from PM4Py 2.7.22.

Only public entry points are called; no native code runs. Seeded logs whose
traces shuffle, drop and repeat activities are mined with the public
`discover_powl`, and the resulting POWL models are converted to workflow nets
with `convert_to_petri_net`. The capture keeps nets that the public
`convert_to_powl` converts but `convert_to_process_tree` rejects: partial
orders over choice and loop nodes that are not series-parallel. Each net is
recorded with its complete language up to four visible events, checked to equal
the language of the reference's converted POWL model.

It also keeps heuristics nets of the tree capture's seeded playouts that
`convert_to_process_tree` converts but `convert_to_powl` rejects (a loop whose
redo part leaves from a place the sequence continues from), each with its
language up to four visible events, which the reference tree shares.

    python -I -B scripts/capture-workflow-net-powl-reference.py \\
        --output src/backend/tests/workflow_net_powl_reference_cases.inc
"""
import argparse
import importlib.util
import os
import random
import sys
import warnings
from pathlib import Path

if os.environ.get("PYTHONHASHSEED") != "0":
    os.environ["PYTHONHASHSEED"] = "0"
    os.execv(sys.executable, [sys.executable] + sys.orig_argv[1:])

warnings.filterwarnings("ignore")

import pm4py  # noqa: E402
from pm4py.objects.log.obj import Event, EventLog, Trace  # noqa: E402

_spec = importlib.util.spec_from_file_location(
    "tree_capture", Path(__file__).with_name("capture-workflow-net-tree-reference.py"))
_tree_capture = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_tree_capture)
compact_pnml = _tree_capture.compact_pnml
cpp_string = _tree_capture.cpp_string
language = _tree_capture.language

MAX_LENGTH = 4
SEEDS = range(0, 400)
CASE_COUNT = 5
TREE_ONLY_SEEDS = range(1000, 1400)
TREE_ONLY_COUNT = 4
TREE_ONLY_MAX_TRANSITIONS = 12


def seeded_log(seed):
    """Traces over a prefix of the alphabet, shuffled, thinned and padded."""
    generator = random.Random(seed)
    activities = "abcdefg"[:generator.randint(3, 6)]
    log = EventLog()
    for _ in range(generator.randint(5, 30)):
        trace = Trace()
        base = list(activities[:generator.randint(2, len(activities))])
        if generator.random() < 0.5:
            generator.shuffle(base)
        if generator.random() < 0.3 and len(base) > 2:
            base.pop(generator.randrange(len(base)))
        if generator.random() < 0.2:
            base.insert(generator.randrange(len(base) + 1), generator.choice(activities))
        for activity in base:
            trace.append(Event({"concept:name": activity}))
        log.append(trace)
    return log


def converts_to_powl(net, initial, final):
    try:
        pm4py.convert_to_powl(net, initial, final)
    except Exception:  # noqa: BLE001 - the reference raises plain exceptions
        return False
    return True


def converts_to_tree(net, initial, final):
    try:
        pm4py.convert_to_process_tree(net, initial, final)
    except Exception:  # noqa: BLE001 - the reference raises plain exceptions
        return False
    return True


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--output", type=Path, required=True)
    arguments = parser.parse_args()

    lines = [
        "// Generated by scripts/capture-workflow-net-powl-reference.py from public",
        "// PM4Py 2.7.22: workflow nets of discovered POWL models that",
        "// convert_to_powl converts and convert_to_process_tree rejects, each with",
        "// its complete language up to four visible events, which the reference",
        "// convert_to_powl result shares.",
        "const std::vector<ReferenceWorkflowCase> kReferencePowlWorkflowCases{",
    ]
    count = 0
    for seed in SEEDS:
        net, initial, final = pm4py.convert_to_petri_net(
            pm4py.discover_powl(seeded_log(seed)))
        if converts_to_tree(net, initial, final):
            continue
        powl = pm4py.convert_to_powl(net, initial, final)
        traces = language(net, initial, final, MAX_LENGTH)
        if traces != language(*pm4py.convert_to_petri_net(powl), MAX_LENGTH):
            raise RuntimeError(f"reference POWL language differs for seed {seed}")
        rows = ",\n      ".join(
            "{" + ", ".join(cpp_string(activity) for activity in trace) + "}"
            for trace in sorted(traces))
        lines.append(f"  {{{cpp_string(f'discovered POWL net of seed {seed}')},\n   "
                     f"{cpp_string(compact_pnml(net, initial, final))},\n   {{{rows}}}}},")
        count += 1
        if count == CASE_COUNT:
            break
    if count != CASE_COUNT:
        raise RuntimeError("not enough POWL-only nets")
    lines.append("};")

    lines.append("// Workflow nets the reference converts to a process tree (with this")
    lines.append("// language) but not to POWL.")
    lines.append("const std::vector<ReferenceWorkflowCase> kReferencePowlRejectedTreeCases{")
    count = 0
    for seed in TREE_ONLY_SEEDS:
        net, initial, final = pm4py.discover_petri_net_heuristics(
            _tree_capture.seeded_log(seed))
        if (len(net.transitions) > TREE_ONLY_MAX_TRANSITIONS or
                not _tree_capture.is_workflow_shape(net) or
                not converts_to_tree(net, initial, final) or
                converts_to_powl(net, initial, final)):
            continue
        tree = pm4py.convert_to_process_tree(net, initial, final)
        traces = language(net, initial, final, MAX_LENGTH)
        if traces != language(*pm4py.convert_to_petri_net(tree), MAX_LENGTH):
            raise RuntimeError(f"reference tree language differs for seed {seed}")
        rows = ",\n      ".join(
            "{" + ", ".join(cpp_string(activity) for activity in trace) + "}"
            for trace in sorted(traces))
        lines.append(f"  {{{cpp_string(f'heuristics net of seed {seed}')},\n   "
                     f"{cpp_string(compact_pnml(net, initial, final))},\n   {{{rows}}}}},")
        count += 1
        if count == TREE_ONLY_COUNT:
            break
    if count != TREE_ONLY_COUNT:
        raise RuntimeError("not enough tree-only nets")
    lines.append("};")
    arguments.output.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
