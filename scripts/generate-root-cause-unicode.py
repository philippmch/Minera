"""Regenerate Unicode 14 categorical and numeric conversion tables.

Only Unicode categories L/M/N/P/S and ASCII space are printable. The table is
generated from the standard Unicode database, independently of mining code.
Run with a Python runtime providing Unicode 14.0.0.
"""

from pathlib import Path
import unicodedata

if unicodedata.unidata_version != "14.0.0":
    raise SystemExit("This artifact requires Unicode 14.0.0")

ranges = []
start = None
for codepoint in range(0x110000):
    printable = codepoint == 32 or unicodedata.category(chr(codepoint))[0] in "LMNPS"
    if not printable and start is None:
        start = codepoint
    if printable and start is not None:
        ranges.append((start, codepoint - 1))
        start = None
if start is not None:
    ranges.append((start, 0x10FFFF))

output = """#pragma once

// Generated by scripts/generate-root-cause-unicode.py from Unicode 14.0.0.
// Printability, decimal digits, and spaces preserve attribute representations.
#include <array>
#include <cstddef>

namespace minera {
inline bool root_cause_unicode_printable(char32_t codepoint) {
  static constexpr std::array<std::array<char32_t, 2>, RANGE_COUNT> ranges{{
""".replace("RANGE_COUNT", str(len(ranges)))
output += "".join(f"    {{{hex(first)}, {hex(last)}}},\n" for first, last in ranges)
output += """  }};
  if (codepoint > 0x10ffff) return false;
  std::size_t first = 0, last = ranges.size();
  while (first < last) {
    const auto middle = first + (last - first) / 2;
    if (ranges[middle][1] < codepoint) first = middle + 1;
    else last = middle;
  }
  return first == ranges.size() || codepoint < ranges[first][0];
}
"""
decimal_starts = [codepoint for codepoint in range(0x110000)
                  if unicodedata.decimal(chr(codepoint), None) == 0]
spaces = [codepoint for codepoint in range(128, 0x110000) if chr(codepoint).isspace()]
output += "inline int root_cause_unicode_decimal(char32_t codepoint) {\n"
output += f"  static constexpr std::array<char32_t, {len(decimal_starts)}> starts{{{{\n"
output += "".join(f"    {hex(codepoint)},\n" for codepoint in decimal_starts)
output += """  }};
  for (const auto first : starts)
    if (codepoint >= first && codepoint < first + 10) return static_cast<int>(codepoint - first);
  return -1;
}
inline bool root_cause_unicode_space(char32_t codepoint) {
  switch (codepoint) {
"""
output += "".join(f"    case {hex(codepoint)}:\n" for codepoint in spaces)
output += """      return true;
    default: return false;
  }
}
}  // namespace minera
"""
destination = Path(__file__).resolve().parent.parent / "src/backend/root_cause_unicode.hpp"
destination.write_text(output, encoding="utf-8", newline="\n")
print(f"Generated {len(ranges)} nonprintable ranges")
