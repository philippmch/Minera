"""Write the LLM log-abstraction bank fixture read by
minera_llm_abstractions_parity_tests.

    python scripts/generate-llm-abstractions-bank-tests.py \\
        docs/llm-abstractions-bank.json.gz \\
        --output src/backend/tests/fixtures/llm_abstractions_bank.txt

Line format: `C <name>`; one `T <region> <priority> <urgent> <event>...` line
per trace, an event being `activity;second;resource;level;amount;kind;flag;code`
with `-` for a missing value, `0`/`1` for the flag and `s:`/`i:` before a
string or integer code; then per call `K <call>` followed by `X <Error>` or by
one `O <text>` line per distinct observation, the text with backslashes and
newlines escaped as `\\\\` and `\\n`.
"""
import argparse
import gzip
import hashlib
import json
from pathlib import Path


def escape(text):
    return text.replace('\\', '\\\\').replace('\n', '\\n')


def event_token(event):
    def get(key, render=str):
        return render(event[key]) if key in event else '-'
    return ';'.join([event['activity'], str(event['second']), event['resource'], str(event['level']),
                     get('amount', repr), get('kind'), get('flag', lambda v: '1' if v else '0'),
                     get('code', lambda v: ('s:' if isinstance(v, str) else 'i:') + str(v))])


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('bank', type=Path)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    raw = args.bank.read_bytes()
    bank = json.loads(gzip.decompress(raw))
    lines = [f'# Generated by scripts/generate-llm-abstractions-bank-tests.py from {args.bank.as_posix()}',
             f'# Bank SHA256 {hashlib.sha256(raw).hexdigest()}; do not edit.']
    for case in bank['cases']:
        lines.append(f"C {case['name']}")
        for trace in case['traces']:
            lines.append(' '.join(['T', trace['region'], str(trace['priority']), '1' if trace['urgent'] else '0']
                                  + [event_token(event) for event in trace['events']]))
        for call in bank['calls']:
            outcome = case['calls'][call]
            lines.append(f'K {call}')
            if 'error' in outcome:
                lines.append(f"X {outcome['error']}")
                continue
            for observed in outcome.get('observed', [outcome]):
                lines.append('O ' + escape(observed['text']))
    args.output.write_text('\n'.join(lines) + '\n', encoding='utf-8')


if __name__ == '__main__':
    main()
