"""Write the trace-attribute clustering bank fixture used by
minera_trace_attribute_clustering_parity_tests.

    python scripts/generate-trace-attribute-clustering-bank-tests.py \\
        docs/trace-attribute-clustering-bank.json.gz \\
        --output src/backend/tests/trace_attribute_clustering_bank_cases.inc

Each case becomes `C <name>`, one `T <value> <activity>...` line per trace
(value `s:<text>`, `i:<integer>` or `-` when missing) and one
`R <variant> <tree> <leaf>...` line per outcome, where a tree is written as
`name[child|child]`; a raising call is `R <variant> !<Error>`. A
`D <variant> <distance>...` line carries the condensed group distances.
"""
import argparse
import gzip
import hashlib
import json
from pathlib import Path


def tree_text(node):
    return node['name'] + '[' + '|'.join(tree_text(child) for child in node['children']) + ']'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('bank', type=Path)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    raw = args.bank.read_bytes()
    bank = json.loads(gzip.decompress(raw))
    lines = []
    for case in bank['cases']:
        lines.append(f"C {case['name']}")
        for trace in case['traces']:
            value = trace['value']
            token = '-' if value is None else f'i:{value}' if isinstance(value, int) else f's:{value}'
            lines.append(' '.join(['T', token] + trace['activities']))
        for variant, call in case['calls'].items():
            for outcome in call.get('observed', [call]):
                if 'error' in outcome:
                    lines.append(f"R {variant} !{outcome['error']}")
                else:
                    lines.append(' '.join(['R', variant, tree_text(outcome['tree'])] + outcome['leaves']))
                    if 'distances' in outcome:
                        lines.append(' '.join(['D', variant] + [repr(d) for d in outcome['distances']]))
    body = ''.join(f'"{line}",\n' for line in lines)
    args.output.write_text(
        '// Generated by scripts/generate-trace-attribute-clustering-bank-tests.py from\n'
        f'// {args.bank.as_posix()}; do not edit.\n'
        f'// Bank SHA256 {hashlib.sha256(raw).hexdigest()}.\n' + body, encoding='utf-8')
    print(f'{len(lines)} lines')


if __name__ == '__main__':
    main()
