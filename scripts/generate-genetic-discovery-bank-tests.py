#!/usr/bin/env python3
"""Write src/backend/tests/genetic_discovery_bank_cases.inc from the bank.

Every case becomes a few space-separated lines (activity names never contain
spaces or commas); test_genetic_discovery_parity.cpp parses them. Partitions
are comma-joined members, "-" marks an empty list.
"""

import gzip
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
BANK = ROOT / "docs" / "genetic-discovery-bank.json.gz"
OUT = ROOT / "src" / "backend" / "tests" / "genetic_discovery_bank_cases.inc"


def joined(values):
    return ",".join(values) if values else "-"


def matrix_lines(matrix):
    lines = ["T " + " ".join(matrix["T"])]
    for tag in ("I", "O"):
        for key, partitions in matrix[tag].items():
            lines.append(" ".join([tag, key] + [joined(p) for p in partitions]))
    return lines


def net_lines(result):
    # Place keys contain commas, so arc lists use semicolons.
    lines = ["P " + key for key in result["places"]]
    for label, inputs, outputs in result["transitions"]:
        lines.append(" ".join(["X", label if label is not None else "-",
                               ";".join(inputs) or "-", ";".join(outputs) or "-"]))
    return lines


def order_lines(order):
    # Transition keys contain spaces: they are written with '/' and joined by '|'.
    return ["A " + place + " " + ("|".join(k.replace(" ", "/") for k in keys) or "-")
            for place, keys in sorted(order.items()) if len(keys) > 1]


def name_lines(names):
    # Only names that differ from the sorted-member spelling the native side
    # derives by itself are written; spaces become '/'.
    return ["N " + key + " " + name.replace(" ", "/") for key, name in sorted(names.items())
            if name != derived_name(key)]


def frozen(members):
    return "frozenset({" + ", ".join(repr(m) for m in members) + "})"


def derived_name(key):
    if key in ("i", "o"):
        return key
    kind, middle, last = key.split(":")
    if kind == "p":
        return "(" + frozen(middle.split(",")) + ", " + frozen(last.split(",")) + ")"
    return kind + "(" + repr(middle) + ", " + frozen(last.split(",")) + ")"


def case_lines(case):
    kind = case["kind"]
    head = f"C {case['name']} {kind}"
    result = case.get("result")
    if isinstance(result, dict) and result.get("error"):
        error = ["E " + result["error"][0] + " " + result["error"][1]]
    else:
        error = None
    if kind == "sources":
        return [head] + matrix_lines(case["matrix"]) + [
            "RS " + " ".join(result[0]), "RK " + " ".join(result[1])]
    if kind == "net":
        if error:
            return [head] + matrix_lines(case["matrix"]) + error
        return [head] + matrix_lines(case["matrix"]) + net_lines(result) + [
            "M " + " ".join(result["im"]), "F " + " ".join(result["fm"])]
    if kind == "partition":
        lines = [f"{head} {case['op']} {case['key']} {case['transition']}"]
        lines += [" ".join(["I", key] + [joined(p) for p in parts]) for key, parts in case["map"].items()]
        lines += [" ".join(["R", key] + [joined(p) for p in parts]) for key, parts in result.items()]
        return lines
    if kind == "fitness":
        lines = [head] + ["L " + " ".join(t) for t in case["traces"]]
        for matrix, order, names in zip(case["population"], result["arc_orders"], result["place_names"]):
            lines += ["G"] + matrix_lines(matrix) + order_lines(order) + name_lines(names)
        return lines + ["V " + " ".join(result["fitness"]), "Q " + " ".join(map(str, result["order"])),
                        "W " + " ".join(result["sorted"])]
    if kind == "operator":
        return [f"{head} {case['op']}"] + matrix_lines(case["matrix"])
    lines = [head] + ["L " + " ".join(t) for t in case["traces"]]
    if error:
        return lines + error
    return lines + net_lines(result) + order_lines(result["arc_order"]) + name_lines(result["place_names"]) + [
        "B " + result["best"]]


def main():
    bank = json.load(gzip.open(BANK, "rt"))
    lines = []
    for case in bank["cases"]:
        lines += case_lines(case)
    with open(OUT, "w") as handle:
        handle.write("// Generated by scripts/generate-genetic-discovery-bank-tests.py; do not edit.\n")
        for line in lines:
            handle.write(json.dumps(line) + ",\n")
    print(OUT, len(lines), "lines", file=sys.stderr)


if __name__ == "__main__":
    main()
