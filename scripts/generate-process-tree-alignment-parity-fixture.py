"""Generate the C++ fixture for the process-tree alignment parity contracts.

Reads merged reference banks written by merge-conformance-parity-reference.py
and emits src/backend/tests/process_tree_alignment_parity_cases.inc with the
"tree:<VARIANT>" observations of every case that has a process tree: per
variant either the reference error, or per trace the admissible
(cost, fitness) pairs observed across the merged runs. Calls that hit the
capture's time limit bind nothing and are skipped. Each case gets its own
builder function so that MSVC never sees one huge initializer.
"""
import argparse
import gzip
import hashlib
import json
from pathlib import Path

VARIANTS = {
    "SEARCH_GRAPH_PT": "kSearchGraphPt",
    "DYNAMIC_PROGRAMMING": "kDynamicProgramming",
    "MILP": "kMilp",
    "APPROXIMATED_ORIGINAL": "kApproximatedOriginal",
}


def s(value):
    return json.dumps(value)


def num(value):
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise TypeError(value)
    return repr(float(value))


def values(entry):
    return [entry["stable"]] if "stable" in entry else entry["unstable"]


def case_function(index, bank, case):
    out = [f"MINERA_TREE_PARITY_NOINLINE TreeParityCase tree_parity_case_{index}() {{",
           "  TreeParityCase c;",
           f"  c.bank = {s(bank)};",
           f"  c.name = {s(case['name'])};",
           f"  c.tree = {s(case['tree'])};",
           "  c.traces = {" + ",".join("{" + ",".join(s(a) for a in t) + "}"
                                       for t in case["traces"]) + "};"]
    for family, variant in VARIANTS.items():
        entry = case["observations"].get("tree:" + family)
        if entry is None:
            continue
        runs = values(entry)
        if any("timeout" in run for run in runs):
            out.append(f"  // tree:{family}: reference timed out")
            continue
        if all("error" in run for run in runs):
            out.append(f"  c.variants.push_back({{ProcessTreeAlignmentVariant::{variant},true,{{}}}});")
            continue
        if any("error" in run for run in runs):
            raise ValueError(f"{case['name']} tree:{family}: mixed outcomes")
        rows = []
        for trace in range(len(case["traces"])):
            seen = []
            for run in runs:
                row = run["result"][trace]
                pair = (float(row["cost"]), float(row["fitness"]))
                if pair not in seen:
                    seen.append(pair)
            rows.append("{" + ",".join("{" + num(c) + "," + num(f) + "}" for c, f in seen) + "}")
        out.append(f"  c.variants.push_back({{ProcessTreeAlignmentVariant::{variant},false,{{"
                   + ",".join(rows) + "}});")
    out += ["  return c;", "}"]
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("banks", type=Path, nargs="+")
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    lines = ["// Generated by scripts/generate-process-tree-alignment-parity-fixture.py; do not edit."]
    cases = []
    for path in args.banks:
        raw = path.read_bytes()
        bank = json.loads(gzip.decompress(raw))
        lines += [
            f"// Reference bank {path.name} SHA256 {hashlib.sha256(raw).hexdigest()}",
            f"//   {bank['reference_version']} at {bank['reference_commit']}, {bank.get('corpus', 'trees')} "
            f"corpus seed {bank['seed']}, {len(bank['runs'])} merged capture runs.",
        ]
        cases += [(path.name, case) for case in bank["cases"] if case.get("tree")]
    lines += [
        "#if defined(_MSC_VER)",
        "#define MINERA_TREE_PARITY_NOINLINE __declspec(noinline)",
        "#else",
        "#define MINERA_TREE_PARITY_NOINLINE __attribute__((noinline))",
        "#endif",
    ]
    for index, (bank, case) in enumerate(cases):
        lines.append(case_function(index, bank, case))
    lines.append("inline std::vector<TreeParityCase> tree_parity_cases() {")
    lines.append("  std::vector<TreeParityCase> cases;")
    for index in range(len(cases)):
        lines.append(f"  cases.push_back(tree_parity_case_{index}());")
    lines.append("  return cases;")
    lines.append("}")
    lines.append("#undef MINERA_TREE_PARITY_NOINLINE")
    args.output.write_text("\n".join(lines) + "\n", newline="\n")


if __name__ == "__main__":
    main()
