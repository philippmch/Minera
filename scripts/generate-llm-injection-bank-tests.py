"""Write the LLM knowledge-injection bank fixture used by
minera_llm_injection_parity_tests.

    python scripts/generate-llm-injection-bank-tests.py \\
        docs/llm-injection-bank.json.gz \\
        --output src/backend/tests/llm_injection_bank_cases.inc

Each call becomes one `{function, source, parameters, variant, expected}`
initializer; strings are escaped byte by byte.
"""
import argparse
import gzip
import hashlib
import json
from pathlib import Path


def quote(text):
    out = []
    for byte in text.encode('utf-8'):
        char = chr(byte)
        if char == '\\' or char == '"':
            out.append('\\' + char)
        elif char == '\n':
            out.append('\\n')
        elif 32 <= byte < 127:
            out.append(char)
        else:
            out.append(f'\\{byte:03o}')
    return '"' + ''.join(out) + '"'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('bank', type=Path)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    raw = args.bank.read_bytes()
    bank = json.loads(gzip.decompress(raw))
    lines = []
    for call in bank['calls']:
        assert 'result' in call, call
        lines.append('{%s, %s, %s, %s, %s},' % (
            quote(call['function']), quote(call['source']), quote(call['parameters']),
            quote(call['variant'] or ''), quote(call['result'])))
    args.output.write_text(
        '// Generated by scripts/generate-llm-injection-bank-tests.py from\n'
        f'// {args.bank.as_posix()}; do not edit.\n'
        f'// Bank SHA256 {hashlib.sha256(raw).hexdigest()}.\n' + '\n'.join(lines) + '\n',
        encoding='utf-8')
    print(f'{len(lines)} calls')


if __name__ == '__main__':
    main()
