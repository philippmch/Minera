"""Generate str.isdigit, str.isalpha and str.isspace classifiers from public Python character predicates."""
from pathlib import Path
import sys
import unicodedata

root = Path(__file__).resolve().parent.parent
assert sys.version_info[:2] == (3, 11) and unicodedata.unidata_version == '14.0.0'


def ranges(predicate):
    out, first = [], None
    for codepoint in range(0x110000):
        accepted = predicate(chr(codepoint))
        if accepted and first is None: first = codepoint
        if not accepted and first is not None:
            out.append((first, codepoint - 1))
            first = None
    if first is not None: out.append((first, 0x10ffff))
    return out


lines = ['#pragma once', '', '// Generated by scripts/generate-python-str-classes.py from public Python 3.11 /',
         '// Unicode 14.0.0 character predicates (str.isdigit, str.isalpha, str.isspace).', '#include <array>',
         '#include <cstddef>', '', 'namespace minera::detail {', '',
         'template <std::size_t N>', 'bool python_class_contains(const std::array<std::array<char32_t, 2>, N>& ranges, char32_t codepoint) {',
         '  std::size_t first = 0, last = ranges.size();', '  while (first < last) {',
         '    const auto middle = first + (last - first) / 2;',
         '    if (ranges[middle][1] < codepoint) first = middle + 1;', '    else last = middle;', '  }',
         '  return first < ranges.size() && codepoint >= ranges[first][0];', '}']
for name, predicate in (('digit', str.isdigit), ('alpha', str.isalpha), ('space', str.isspace)):
    found = ranges(predicate)
    lines += ['', f'inline bool python_is{name}(char32_t codepoint) {{',
              f'  static constexpr std::array<std::array<char32_t, 2>, {len(found)}> ranges{{{{']
    lines += ['    {0x' + format(a, 'x') + ', 0x' + format(b, 'x') + '},' for a, b in found]
    lines += ['  }};', '  return python_class_contains(ranges, codepoint);', '}']
lines += ['', '}  // namespace minera::detail', '']
(root / 'src/backend/python_str_classes.hpp').write_text('\n'.join(lines), encoding='utf-8', newline='\n')
