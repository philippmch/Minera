"""Turns docs/case-relations-bank.json.gz into
src/backend/tests/case_relations_bank_cases.hpp for
src/backend/tests/test_case_relations_parity.cpp: every case's three input
tables (with their pandas dtypes), the options of its parameter set, and the
expected output table and index labels or the fact that the call raised.

    python -I -B scripts/generate-case-relations-bank-tests.py \
        docs/case-relations-bank.json.gz \
        --output src/backend/tests/case_relations_bank_cases.hpp
"""
import argparse
import gzip
import hashlib
import importlib.util
import json
from pathlib import Path

spec = importlib.util.spec_from_file_location(
    'reference_tests', Path(__file__).with_name('generate-case-relations-reference-tests.py'))
reference = importlib.util.module_from_spec(spec)
spec.loader.exec_module(reference)
quote = reference.quote

OPTIONS = {
    'default': {'case_id_key': 'case:concept:name', 'timestamp_key': 'time:timestamp'},
    'custom': {'case_id_key': 'cid', 'timestamp_key': 'ts', 'left_suffix': '_L', 'right_suffix': '_R'},
}


def table(frame):
    columns = frame['columns']
    dtypes = ', '.join(quote(frame['dtypes'][column]) for column in columns)
    return 'typed(' + reference.table(frame) + ', {' + dtypes + '})'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('bank', type=Path)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    raw = args.bank.read_bytes()
    bank = json.loads(gzip.decompress(raw))
    out = ['// Generated by scripts/generate-case-relations-bank-tests.py from',
           f'// {args.bank.as_posix()}; do not edit.',
           f'// Bank SHA256 {hashlib.sha256(raw).hexdigest()}.',
           '#pragma once',
           '#include "case_relations_reference_cases.hpp"',
           '#include <cstdint>', '#include <string>', '#include <vector>', '',
           'namespace case_relations_bank {',
           'using namespace case_relations_reference;', '',
           'struct BankCase {',
           '  std::string name, config;',
           '  EventTable base, incoming, relations;',
           '  bool raises = false;',
           '  EventTable expected;',
           '  std::vector<std::int64_t> index;',
           '};', '',
           'inline EventTable typed(EventTable table, std::vector<std::string> dtypes) {',
           '  table.dtypes = std::move(dtypes);',
           '  return table;',
           '}', '',
           'inline CaseRelationsOptions options_for(const std::string& config) {',
           '  CaseRelationsOptions options;']
    for config, values in OPTIONS.items():
        out.append(f'  if (config == {quote(config)}) {{')
        for key, value in values.items():
            out.append(f'    options.{key} = {quote(value)};')
        out.append('  }')
    out += ['  return options;', '}', '']
    # One function per case keeps each translation step small.
    count = 0
    for case in bank['cases']:
        for config, call in case['calls'].items():
            if 'observed' in call:
                raise SystemExit(f'{case["name"]} {config} varies across hash seeds')
            out.append(f'inline BankCase case_{count}() {{')
            out.append('  BankCase item;')
            out.append(f'  item.name = {quote(case["name"])};')
            out.append(f'  item.config = {quote(config)};')
            for side in ('base', 'incoming', 'relations'):
                out.append(f'  item.{side} = {table(call[side + "_input"])};')
            if 'error' in call:
                out.append('  item.raises = true;')
            else:
                out.append(f'  item.expected = {table(call["result"])};')
                labels = [record['index'] for record in call['result']['records']]
                out.append('  item.index = {' + ', '.join(f'std::int64_t{{{label}}}' for label in labels) + '};')
            out.append('  return item;')
            out.append('}')
            count += 1
    out.append('')
    out.append('inline std::vector<BankCase> cases() {')
    out.append('  return {' + ', '.join(f'case_{n}()' for n in range(count)) + '};')
    out.append('}')
    out.append('')
    out.append('}  // namespace case_relations_bank')
    args.output.write_text('\n'.join(out) + '\n', encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
