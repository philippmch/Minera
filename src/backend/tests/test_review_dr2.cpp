int main() {
  int failures = 0;
  std::size_t calls = 0;
  for (std::size_t c = 0; c < kCases.size(); ++c) {
    const auto log = import(kCases[c].csv);
    for (const auto& call : kCases[c].calls) {
      ++calls;
      LinkAnalysisOptions options;
      options.out_column = "doc";
      options.in_column = "ref";
      options.look_forward = call.flags[0] == '1';
      options.keep_first_occurrence = call.flags[1] == '1';
      options.propagate = call.flags[2] == '1';
      std::string seen;
      bool raised = false;
      try {
        seen = pairs(discover_link_analysis(log, options), options.propagate);
      } catch (const std::exception& error) {
        raised = true;
        seen = error.what();
      }
      const std::string expected = call.expected;
      const bool ok = call.error ? raised && seen.find(expected) != std::string::npos : !raised && seen == expected;
      if (ok) continue;
      ++failures;
      std::cerr << "case " << c << " flags " << call.flags << ":\n  seen     " << seen << "\n  expected " << expected << "\n";
    }
  }
  std::cout << calls << " link analysis calls compared, " << failures << " failed\n";
  return failures == 0 && calls == 208 ? 0 : 1;
}
